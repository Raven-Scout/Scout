"""Is the session holding the vault lock making progress? One answer for the reaper, run health and the app.

A scheduled run's log is no progress signal. ``claude -p`` prints nothing until
it exits, and on a vault linked to Agnes the lease keepalive appends a line
every five minutes for as long as the runner shell lives, whether or not claude
does anything. Reading the log's mtime as progress (the lock reaper since #476,
the app since #701) meant a hung claude behind a live shell was never judged
wedged and showed as Running for ever.

So a watcher runs beside every scheduled run (``scoutctl progress watch``,
started by ``scripts/scout-lock.sh`` once the run holds the session lock). Every
``SCOUT_PROGRESS_SAMPLE_SECS`` it samples the runner's session, the way the
reaper samples a holder: the processes of the runner's process group and
process tree, minus Scout's own background helpers (the lease keepalive, the
run brokers, the watcher itself) and everything they start. The session made
progress when its process list changed (a tool call started or ended) or it
burned ``SCOUT_LOCK_PROGRESS_CPU_SECS`` of CPU within the last
:data:`CPU_WINDOW_SECS` of awake time. The window is sliding, not "since the last
progress": a hung ``claude -p`` still burns a trickle of CPU (timers, sockets),
and summed over two hours a trickle reaches any threshold. A helper does
neither on claude's behalf, so it no longer counts. A sample ``ps`` can't take
(an error, a timeout, a table without the runner) says nothing either way: no
progress, and no stall for that gap; after :data:`MAX_FAILED_SAMPLES` of them in
a row the watcher withdraws its line until ``ps`` works again, and waiters
sample the holder themselves.

The watcher writes what it found to ``.scout-logs/.scout-session.lock.alive``
after every sample (through :mod:`scout.safe_write`, so a link planted in
``.scout-logs`` is never written through), one line::

    1 <runner pid> <last progress, epoch s> <stalled awake s> <fresh for s> <run log path>

The stall counts only awake time (``scout.agent_runtimes.awake``), so a laptop
asleep mid-run is not stalled. The file's mtime is the last sample: a reader
trusts the line only while ``0 <= now - mtime <= fresh for`` (give or take
:data:`FRESH_SLACK_SECS`), with *fresh for* capped at :data:`MAX_FRESH_SECS`
whatever the line says, so a watcher that died (or a host that just woke) is
never read as a stall, and a line a run forged goes stale like any other.
Readers open it without following links or blocking, and read at most
:data:`MAX_LINE_BYTES`:

- ``scripts/scout-lock.sh``'s ``_scout_holder_wedged``: a holder is wedged once
  its fresh line's stall passes ``SCOUT_LOCK_MAX_AGE_SECS``. Without a fresh
  line for the holder it samples CPU and the process list itself, as before.
- ``scoutctl health``: ``session.no_progress`` for the same holder on the same
  ceiling (:func:`scout.health.progress_findings`).
- The macOS app (``RunProgress.swift``): a running run is "Didn't finish" once
  its fresh line's stall passes the run type's cutoff.

The format is a contract: ``tests/fixtures/contract/run-progress.alive`` is
generated by ``tests/unit/test_run_progress.py`` and byte-copied to the app.
"""

from __future__ import annotations

import contextlib
import os
import re
import stat
import subprocess
import time
from collections import deque
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from scout import safe_write
from scout.agent_runtimes import awake

FORMAT_VERSION = 1
HEARTBEAT_SUFFIX = ".alive"
LOCK_NAME = ".scout-session.lock"

SAMPLE_SECS_ENV = "SCOUT_PROGRESS_SAMPLE_SECS"
CPU_SECS_ENV = "SCOUT_LOCK_PROGRESS_CPU_SECS"  # the reaper's knob: one threshold for both
MAX_AGE_SECS_ENV = "SCOUT_LOCK_MAX_AGE_SECS"  # the reaper's ceiling
DEFAULT_SAMPLE_SECS = 60
MAX_SAMPLE_SECS = 200
DEFAULT_CPU_SECS = 10
DEFAULT_MAX_AGE_SECS = 7200
# The CPU threshold must be burned within this much awake time, however often the watcher samples.
CPU_WINDOW_SECS = 600
# A line is trusted for this many samples, plus slack for a slow `ps` on a loaded host.
FRESH_SAMPLES = 3
FRESH_SLACK_SECS = 30
# Readers never trust a line longer than this, whatever it says: the longest a real watcher asks for
# (three samples at the slowest rate it allows, plus the slack), a little over ten minutes.
MAX_FRESH_SECS = FRESH_SAMPLES * MAX_SAMPLE_SECS + FRESH_SLACK_SECS
# After this many samples in a row that `ps` couldn't take, the watcher withdraws its line until one
# succeeds: a line kept fresh with a frozen stall would vouch for a run nobody is measuring.
MAX_FAILED_SAMPLES = 3
MAX_LINE_BYTES = 4096

# Scout's own background helpers in a run's session. They live as long as the
# runner and burn CPU or log on their own schedule, so neither says the agent
# moved; their descendants go with them. A helper is a process whose argv
# STARTS as the engine with one of these subcommands -- `[interpreter [flags]]
# …/scoutctl <sub>` or `python [flags] -m scout[.cli] <sub>` -- never one that
# merely mentions it: claude's and the retry wrapper's argv carry the whole
# prompt, and a prompt that says "broker serve" must not hide claude's tree.
HELPER_SUBCOMMANDS = ("repo lease keepalive", "broker serve", "progress watch")
_HELPER_RE = re.compile(
    r"^(?:\S+\s+){0,5}?(?:(?:\S*/)?scoutctl|-m\s+scout(?:\.cli)?)\s+(?:"
    + "|".join(r"\s+".join(map(re.escape, sub.split())) for sub in HELPER_SUBCOMMANDS)
    + r")(?:\s|$)"
)


def env_secs(name: str, default: int, env: Mapping[str, str] | None = None, *, allow_zero: bool = False) -> int:
    """A whole number of seconds from *env*, else *default*. ``0`` only with *allow_zero*, as the shell takes it."""
    raw = (os.environ if env is None else env).get(name, "")
    if not (raw.isascii() and raw.isdigit()):
        return default
    value = int(raw)
    return value if value > 0 or allow_zero else default


def heartbeat_path(vault: Path) -> Path:
    return vault / ".scout-logs" / (LOCK_NAME + HEARTBEAT_SUFFIX)


def fresh_for(sample_s: int) -> int:
    return FRESH_SAMPLES * sample_s + FRESH_SLACK_SECS


def is_helper(command: str) -> bool:
    return _HELPER_RE.match(command) is not None


# --- the line ---------------------------------------------------------------


@dataclass(frozen=True)
class Heartbeat:
    runner_pid: int
    progress_at: int  # wall-clock epoch seconds of the last progress
    stalled_s: int  # awake seconds since then
    fresh_for_s: int
    log: str

    def render(self) -> str:
        return f"{FORMAT_VERSION} {self.runner_pid} {self.progress_at} {self.stalled_s} {self.fresh_for_s} {self.log}\n"


def parse(text: str) -> Heartbeat | None:
    """The line, or None for anything else (another version, a torn or hand-edited file)."""
    parts = text.rstrip("\n").split(" ", 5)
    if len(parts) != 6 or parts[0] != str(FORMAT_VERSION) or "\n" in parts[5] or not parts[5]:
        return None
    if not all(p.isascii() and p.isdigit() for p in parts[1:5]):
        return None
    pid, progress_at, stalled, fresh = (int(p) for p in parts[1:5])
    if pid <= 0 or fresh <= 0:
        return None
    return Heartbeat(pid, progress_at, stalled, fresh, parts[5])


def _read_line(path: Path) -> tuple[str, float] | None:
    """``(text, mtime)`` of a regular file at *path*, never following a link or blocking on a FIFO."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    except OSError:
        return None
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode):
            return None
        data = os.read(fd, MAX_LINE_BYTES + 1)
        return (data.decode("utf-8"), st.st_mtime) if len(data) <= MAX_LINE_BYTES else None
    except (OSError, UnicodeDecodeError):
        return None
    finally:
        os.close(fd)


def read_fresh(path: Path, *, now: float | None = None) -> Heartbeat | None:
    """The line at *path* while its watcher is alive (sampled within its capped ``fresh for``), else None."""
    got = _read_line(path)
    beat = parse(got[0]) if got else None
    if got is None or beat is None:
        return None
    age = (time.time() if now is None else now) - got[1]
    return beat if -FRESH_SLACK_SECS <= age <= min(beat.fresh_for_s, MAX_FRESH_SECS) else None


def write(path: Path, beat: Heartbeat) -> None:
    """Replace the line at *path* with *beat* through :func:`scout.safe_write.atomic_write_text`.

    A temp file with a random name, made ``O_CREAT | O_EXCL | O_NOFOLLOW``, renamed over the line: nothing a run
    planted in ``.scout-logs`` is ever written through. Mode 0600 (every reader runs as this user), and no fsync:
    the line is rewritten every sample and means nothing after a crash. Best effort: a missed write only makes the
    line go stale, and readers fall back.
    """
    with contextlib.suppress(OSError):  # UnsafeFileError is an OSError too
        safe_write.atomic_write_text(path, beat.render(), mode=0o600, fsync=False)


def remove_if_ours(path: Path, runner_pid: int) -> None:
    """Remove the line if it is still this runner's; a new holder's watcher may own the path now."""
    got = _read_line(path)
    beat = parse(got[0]) if got else None
    if beat is not None and beat.runner_pid == runner_pid:
        with contextlib.suppress(OSError):
            path.unlink()


def lock_pid(lock: Path) -> int | None:
    """The PID in the session lock, or None for a missing, unreadable or unparseable one."""
    got = _read_line(lock)
    text = got[0].strip() if got else ""
    return int(text) if text.isascii() and text.isdigit() else None


# --- sampling the session -----------------------------------------------------


@dataclass(frozen=True)
class Proc:
    pid: int
    ppid: int
    pgid: int
    stat: str
    cpu_cs: int
    command: str


def cpu_centiseconds(text: str) -> int | None:
    """``ps -o time=`` ([[dd-]hh:]mm:ss, hundredths on macOS) in centiseconds."""
    days, _, clock = text.rpartition("-")
    try:
        secs = 0.0
        for part in clock.split(":"):
            secs = secs * 60 + float(part)
        return int((int(days or 0) * 86400 + secs) * 100 + 0.5)
    except ValueError:
        return None


def parse_ps(text: str) -> list[Proc]:
    """Rows of ``ps -A -ww -o pid= -o ppid= -o pgid= -o stat= -o time= -o command=``."""
    out: list[Proc] = []
    for line in text.splitlines():
        parts = line.split(None, 5)
        if len(parts) < 5 or not all(p.isdigit() for p in parts[:3]):
            continue
        cpu = cpu_centiseconds(parts[4])
        if cpu is None:
            continue
        out.append(Proc(int(parts[0]), int(parts[1]), int(parts[2]), parts[3], cpu, parts[5] if len(parts) > 5 else ""))
    return out


def _descendants(procs: Iterable[Proc], roots: set[int]) -> set[int]:
    keep = set(roots)
    rows = list(procs)
    grew = True
    while grew:
        grew = False
        for p in rows:
            if p.ppid in keep and p.pid not in keep:
                keep.add(p.pid)
                grew = True
    return keep


def session_sample(procs: list[Proc], runner_pid: int, *, self_pid: int) -> tuple[int, frozenset[int]]:
    """``(cpu centiseconds, pids)`` of the runner's session without Scout's helpers.

    The session is the runner's process group when it leads one (launchd starts
    each runner as a group leader) plus its process tree, as the reaper reads
    it; zombies are left out. Helpers, this watcher and all they start are not
    the agent's work.
    """
    by_pid = {p.pid: p for p in procs}
    runner = by_pid.get(runner_pid)
    group = runner.pgid if runner is not None and runner.pgid == runner_pid else None
    roots = {runner_pid} | ({p.pid for p in procs if p.pgid == group} if group is not None else set())
    session = _descendants(procs, roots)
    helpers = {p.pid for p in procs if p.pid != runner_pid and (p.pid == self_pid or is_helper(p.command))}
    session -= _descendants(procs, helpers & session)
    live = [by_pid[pid] for pid in session if pid in by_pid and not by_pid[pid].stat.startswith("Z")]
    return sum(p.cpu_cs for p in live), frozenset(p.pid for p in live)


def run_ps() -> str:
    out = subprocess.run(
        ["ps", "-A", "-ww", "-o", "pid=", "-o", "ppid=", "-o", "pgid=", "-o", "stat=", "-o", "time=", "-o", "command="],
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    return out.stdout


def take_sample(ps: Callable[[], str], runner_pid: int, *, self_pid: int) -> tuple[int, frozenset[int]] | None:
    """The session's sample, or None when ``ps`` failed or its table has no row for the runner."""
    try:
        procs = parse_ps(ps())
    except (OSError, subprocess.SubprocessError, UnicodeDecodeError):
        return None
    if not any(p.pid == runner_pid for p in procs):
        return None
    return session_sample(procs, runner_pid, self_pid=self_pid)


# --- the watcher ---------------------------------------------------------------


def _pid_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


class _Progress:
    """The progress rule over successive samples: a changed process list, or the CPU threshold within the window."""

    def __init__(self, cpu_threshold_cs: int, window_s: int) -> None:
        self.threshold = cpu_threshold_cs
        self.window_s = window_s
        self.samples: deque[tuple[str, int, int]] = deque()  # (awake clock, awake s, cpu cs)
        self.pids: frozenset[int] | None = None

    def moved(self, cpu: int, pids: frozenset[int], clock: str, now: int) -> bool | None:
        """True on progress, False on none, None for a baseline (nothing known yet)."""
        prev = self.samples[-1] if self.samples else None
        known = self.pids is not None
        changed = known and pids != self.pids
        # Another set of processes, or another clock (a reboot): old totals and times don't compare.
        if prev is None or pids != self.pids or prev[0] != clock or now < prev[1]:
            self.samples.clear()
        self.samples.append((clock, now, cpu))
        # Keep one sample at or before the window's start: the CPU burned since it is the window's.
        while len(self.samples) > 1 and self.samples[1][1] <= now - self.window_s:
            self.samples.popleft()
        self.pids = pids
        if not known:
            return None
        if changed:
            return True
        # A total that fell means a process went; otherwise the window's CPU.
        return (prev is not None and cpu < prev[2]) or cpu - self.samples[0][2] >= self.threshold


def watch(
    vault: Path,
    *,
    runner_pid: int,
    log: str,
    sample_s: int = DEFAULT_SAMPLE_SECS,
    cpu_threshold_cs: int = DEFAULT_CPU_SECS * 100,
    window_s: int = CPU_WINDOW_SECS,
    self_pid: int | None = None,
    ps: Callable[[], str] = run_ps,
    alive: Callable[[int], bool] = _pid_alive,
    awake_now: Callable[[], tuple[str, int]] = awake.now,
    wall_now: Callable[[], float] = time.time,
    sleep: Callable[[float], None] = time.sleep,
) -> str:
    """Sample *runner_pid*'s session every *sample_s* and keep its line current while it holds the lock.

    Returns why it stopped: ``gone`` (the runner exited) or ``not_holder`` (the
    lock is no longer the runner's). The line goes with it, however it stops
    (the CLI turns SIGTERM into SystemExit), unless another holder's watcher
    has replaced it.
    """
    me = os.getpid() if self_pid is None else self_pid
    sample_s = min(max(sample_s, 1), MAX_SAMPLE_SECS)
    lock = vault / ".scout-logs" / LOCK_NAME
    path = heartbeat_path(vault)
    fresh = fresh_for(sample_s)
    rule = _Progress(cpu_threshold_cs, window_s)
    first = take_sample(ps, runner_pid, self_pid=me)
    last_clock, last = awake_now()
    if first is not None:
        rule.moved(*first, last_clock, last)
    progress_at = int(wall_now())
    stalled = 0
    failed = 0
    try:
        while True:
            if lock_pid(lock) != runner_pid:
                return "not_holder"
            if failed < MAX_FAILED_SAMPLES:
                write(path, Heartbeat(runner_pid, progress_at, stalled, fresh, log))
            else:
                remove_if_ours(path, runner_pid)  # nobody is measuring: let waiters sample for themselves
            sleep(sample_s)
            if not alive(runner_pid):
                return "gone"
            sample = take_sample(ps, runner_pid, self_pid=me)
            clock, now = awake_now()
            failed = failed + 1 if sample is None else 0
            verdict = rule.moved(*sample, clock, now) if sample is not None else None
            if verdict:
                progress_at = int(wall_now())
                stalled = 0
            elif verdict is False and clock == last_clock and now >= last:
                stalled += now - last
            # else no sample, a baseline, or the clock changed or went back (a reboot): no stall is known
            last_clock, last = clock, now
    finally:
        remove_if_ours(path, runner_pid)


