"""Per-note privacy: the policy and the pure classifier (#453).

Spec: ``docs/superpowers/specs/2026-10-20-per-note-privacy-design.md`` §3, §4.2,
§5 and §12.1–12.2.

``classify(rel_path, text, policy)`` turns (path, frontmatter, policy) into a
:class:`Label`. It is a pure function of its arguments so the Agnes indexer can
reproduce every label exactly from the synced files plus the policy JSON.

Policy is data. The engine default is ``scout/defaults/privacy.yaml`` (its JSON
projection, ``scout/privacy.snapshot.json``, is generated by
``python -m scout.scripts.privacy_snapshot``). A vault may add to it with a
``privacy:`` block in its ``scout-config.yaml``; :func:`load_policy` merges the
two. The overlay can only add paths, defaults, shared files and surfaces, and
move a surface to ``shared``. It can't remove ``local_only.always``, and it
can't move an engine-default shared surface to ``owner_only``.

Fail-closed everywhere: an unknown ``visibility`` value, an unparseable
frontmatter block and a frontmatter fence that never closes all classify as
``private``; an unparseable ``federation_scope`` counts as ``none``.

Warning rule ids carried on a :class:`Label` (kb-lint ids, spec §8.2):

- ``visibility-value``: ``visibility`` isn't ``normal``/``private``, or
  ``federation_scope`` doesn't parse.
- ``privacy-contradiction``: the note is private and declares a
  ``federation_scope`` other than ``none``.
- ``frontmatter-unparseable``: the block doesn't parse; the note is private
  with ``visibility_source == "forced"``.
- ``file-unreadable``: the caller passed ``unreadable=True`` (an existing
  markdown file that couldn't be read); private, ``forced``.

Warning rule ids carried on a :class:`Policy` (from the overlay):

- ``federation-reserved``: the overlay sets a Stage 2 key
  (``federation_ceilings``, ``federation_defaults``, ``federation``); ignored.
- ``surface-widen-ignored``: the overlay lists an engine-default shared surface
  under ``owner_only``; ignored.
- ``visibility-value``: an overlay ``visibility_defaults`` entry has a value
  other than ``normal``/``private``; it is kept as ``private``.
- ``privacy-overlay-unreadable``: ``scout-config.yaml`` exists but can't be
  read or parsed (or isn't a mapping); the whole overlay is dropped and the
  engine default applies. Later tasks refuse sync while it is set.
- ``privacy-overlay-invalid``: the ``privacy:`` block or one of its keys has the
  wrong shape; that part is ignored.
"""

from __future__ import annotations

import dataclasses
import os
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from functools import lru_cache
from importlib.resources import as_file, files
from pathlib import Path
from typing import Any, Literal

import yaml

from scout import paths
from scout.kb.frontmatter import FENCE, frontmatter_block
from scout.kb.lint_config import glob_match

SCHEMA_VERSION = 1

VISIBILITIES = ("normal", "private")
Visibility = Literal["normal", "private"]
VisibilitySource = Literal["frontmatter", "path_default", "default", "forced"]
SurfaceClass = Literal["owner_only", "shared"]
# Declared federation scope: "none", "org", or a tuple of principal strings.
FederationScope = str | tuple[str, ...]

_STAGE2_KEYS = ("federation_ceilings", "federation_defaults", "federation")
FULL_READERS = frozenset({"owner", "autonomous"})

_PERSON_RE = re.compile(r"^person:[^\s@,\[\]]+@[^\s@,\[\]]+$", re.IGNORECASE)
_GROUP_RE = re.compile(r"^group:[A-Za-z0-9_-]{1,64}$")

# The vault's Python-importable alias for knowledge-base/ (a symlink).
_KB_DIR = "knowledge-base"
_KB_ALIAS = "knowledge_base"


@dataclass(frozen=True)
class Policy:
    """The effective privacy policy (engine default + vault overlay).

    ``local_only`` is the effective user list (engine ``local_only.default``
    plus the overlay's ``local_only_add``); ``local_only_always`` is kept apart
    because no overlay can remove it. ``sync_allow`` carves paths out of
    ``local_only_always`` only. Lists are first-match-wins where order matters
    (``visibility_defaults``: overlay entries first).
    """

    local_only_always: tuple[str, ...]
    local_only: tuple[str, ...]
    sync_allow: tuple[str, ...]
    visibility_defaults: tuple[tuple[str, str], ...]
    owner_only_surfaces: frozenset[str]
    shared_surfaces: frozenset[str]
    shared_files: tuple[str, ...]
    warnings: tuple[str, ...] = ()

    def to_json(self) -> dict[str, Any]:
        """The policy in ``privacy.yaml``'s shape (``schema_version`` aside).

        ``local_only.default`` holds the *effective* list, overlay additions
        included. Surface ids are sorted (they are sets).
        """
        return {
            "local_only": {
                "always": list(self.local_only_always),
                "default": list(self.local_only),
                "sync_allow": list(self.sync_allow),
            },
            "visibility_defaults": [{"glob": g, "visibility": v} for g, v in self.visibility_defaults],
            "surfaces": {
                "owner_only": sorted(self.owner_only_surfaces),
                "shared": sorted(self.shared_surfaces),
            },
            "shared_files": list(self.shared_files),
            "warnings": list(self.warnings),
        }


@dataclass(frozen=True)
class Label:
    """One file's privacy label (spec §5.4).

    ``federation_scope_declared`` is ``"none"``, ``"org"``, or a tuple of
    principals. Principals are canonicalised: whitespace trimmed, a
    ``person:`` principal lower-cased whole (emails compare
    case-insensitively, §12.2), a ``group:`` id kept as written (it's an
    opaque host id), duplicates dropped in first-seen order. ``to_json``
    renders the tuple as a list. In v1 ``federation_scope`` is always
    ``"none"`` and ``federation_source`` always ``"reserved"``.
    """

    path: str
    visibility: Visibility
    visibility_source: VisibilitySource
    federation_scope: str = "none"
    federation_scope_declared: FederationScope = "none"
    federation_source: Literal["reserved"] = "reserved"
    local_only: bool = False
    shared_file: bool = False
    warnings: tuple[str, ...] = field(default=())

    def to_json(self) -> dict[str, Any]:
        declared = self.federation_scope_declared
        return {
            "path": self.path,
            "visibility": self.visibility,
            "visibility_source": self.visibility_source,
            "federation_scope": self.federation_scope,
            "federation_scope_declared": list(declared) if isinstance(declared, tuple) else declared,
            "federation_source": self.federation_source,
            "local_only": self.local_only,
            "shared_file": self.shared_file,
            "warnings": list(self.warnings),
        }


# ----- policy -----------------------------------------------------------------


def _strs(value: Any) -> tuple[str, ...]:
    return tuple(str(v) for v in value or ())


def _parse_visibility(value: Any) -> Visibility | None:
    """``normal``/``private`` (trimmed, case-insensitive), else None."""
    if isinstance(value, str):
        v = value.strip().lower()
        if v == "normal":
            return "normal"
        if v == "private":
            return "private"
    return None


@lru_cache(maxsize=1)
def _engine_default() -> Policy:
    """Parse the shipped ``privacy.yaml``. A broken file raises: it's a bug."""
    resource = files("scout") / "defaults" / "privacy.yaml"
    with as_file(resource) as path:
        return _parse_engine_yaml(yaml.safe_load(path.read_text(encoding="utf-8")))


def _parse_engine_yaml(raw: dict[str, Any]) -> Policy:
    if raw.get("schema_version") != SCHEMA_VERSION:
        raise ValueError(f"privacy.yaml: unsupported schema_version {raw.get('schema_version')!r}")
    lo = raw["local_only"]
    defaults: list[tuple[str, str]] = []
    for entry in raw["visibility_defaults"]:
        vis = _parse_visibility(entry["visibility"])
        if vis is None:
            raise ValueError(f"privacy.yaml: bad visibility {entry['visibility']!r}")
        defaults.append((str(entry["glob"]), vis))
    return Policy(
        local_only_always=_strs(lo["always"]),
        local_only=_strs(lo.get("default")),
        sync_allow=_strs(lo.get("sync_allow")),
        visibility_defaults=tuple(defaults),
        owner_only_surfaces=frozenset(_strs(raw["surfaces"]["owner_only"])),
        shared_surfaces=frozenset(_strs(raw["surfaces"]["shared"])),
        shared_files=_strs(raw.get("shared_files")),
    )


def _str_list(value: Any) -> tuple[str, ...] | None:
    """A list of strings, or None for the wrong shape."""
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        return None
    return tuple(value)


def _dedup(items: Iterable[str]) -> tuple[str, ...]:
    return tuple(dict.fromkeys(items))


def load_policy(vault: Path | None) -> Policy:
    """Engine default merged with ``<vault>/scout-config.yaml → privacy:``.

    ``vault=None``, a missing config file, or a missing ``privacy:`` key all
    mean the engine default. The overlay keys are ``local_only_add``,
    ``visibility_defaults`` (placed before the engine's, so the owner's entry
    wins), ``shared_files_add`` and ``surfaces: {owner_only, shared}``. See the
    module docstring for the warnings it records on ``Policy.warnings``.
    """
    base = _engine_default()
    if vault is None:
        return base
    config = paths.config_path(vault)
    if not config.exists():
        return base
    try:
        data = yaml.safe_load(config.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return dataclasses.replace(base, warnings=("privacy-overlay-unreadable",))
    if data is None:
        return base
    if not isinstance(data, dict):
        return dataclasses.replace(base, warnings=("privacy-overlay-unreadable",))
    return policy_from_overlay(data.get("privacy"))


def policy_from_overlay(overlay: Mapping[str, Any] | None) -> Policy:
    """Engine default merged with a ``privacy:`` overlay mapping (no vault needed).

    ``None`` means the engine default. This is the merge :func:`load_policy`
    applies, exposed so the contract corpus (and the Agnes indexer's runner)
    can build a policy from a bare overlay. A non-mapping overlay is ignored
    with ``privacy-overlay-invalid``.
    """
    base = _engine_default()
    if overlay is None:
        return base
    warnings: list[str] = []
    if not isinstance(overlay, Mapping):
        return dataclasses.replace(base, warnings=("privacy-overlay-invalid",))

    if any(k in overlay for k in _STAGE2_KEYS):
        warnings.append("federation-reserved")

    local_only = base.local_only
    if "local_only_add" in overlay:
        add = _str_list(overlay["local_only_add"])
        if add is None:
            warnings.append("privacy-overlay-invalid")
        else:
            local_only = _dedup((*local_only, *add))

    vis_defaults = base.visibility_defaults
    if "visibility_defaults" in overlay:
        entries = overlay["visibility_defaults"]
        if not isinstance(entries, list):
            warnings.append("privacy-overlay-invalid")
        else:
            added: list[tuple[str, str]] = []
            for entry in entries:
                if not isinstance(entry, dict) or not isinstance(entry.get("glob"), str):
                    warnings.append("privacy-overlay-invalid")
                    continue
                vis = _parse_visibility(entry.get("visibility"))
                if vis is None:
                    warnings.append("visibility-value")
                    vis = "private"
                added.append((entry["glob"], vis))
            vis_defaults = (*added, *vis_defaults)

    shared_files = base.shared_files
    if "shared_files_add" in overlay:
        add = _str_list(overlay["shared_files_add"])
        if add is None:
            warnings.append("privacy-overlay-invalid")
        else:
            shared_files = _dedup((*shared_files, *add))

    owner_only = set(base.owner_only_surfaces)
    shared = set(base.shared_surfaces)
    if "surfaces" in overlay:
        surfaces = overlay["surfaces"]
        if not isinstance(surfaces, dict):
            warnings.append("privacy-overlay-invalid")
        else:
            want_owner = _str_list(surfaces.get("owner_only", []))
            want_shared = _str_list(surfaces.get("shared", []))
            if want_owner is None or want_shared is None:
                warnings.append("privacy-overlay-invalid")
            else:
                for sid in want_owner:
                    if sid in base.shared_surfaces:
                        warnings.append("surface-widen-ignored")
                    else:
                        owner_only.add(sid)
                shared.update(want_shared)
                owner_only -= shared  # shared wins: the narrower class

    return Policy(
        local_only_always=base.local_only_always,
        local_only=local_only,
        sync_allow=base.sync_allow,
        visibility_defaults=vis_defaults,
        owner_only_surfaces=frozenset(owner_only),
        shared_surfaces=frozenset(shared),
        shared_files=shared_files,
        warnings=_dedup(warnings),
    )


# ----- classifier -------------------------------------------------------------


def _any(globs: tuple[str, ...], rel: str) -> bool:
    return any(glob_match(g, rel) for g in globs)


class _Unparseable(Exception):
    pass


def _frontmatter(text: str | None) -> dict[str, Any] | None:
    """The parsed frontmatter mapping; None when the file has none.

    Raises ``_Unparseable`` when line one is a fence but the block doesn't
    close in ``text``, doesn't parse as YAML, or isn't a mapping. Callers that
    pass a head window must make it long enough to hold the closing fence.
    """
    if text is None:
        return None
    lines = text.removeprefix("﻿").splitlines()
    if not lines or lines[0].rstrip() != FENCE:
        return None
    block = frontmatter_block(lines)
    if block is None:
        raise _Unparseable
    try:
        data = yaml.safe_load("\n".join(block))
    except yaml.YAMLError as e:
        raise _Unparseable from e
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise _Unparseable
    return data


def _parse_principal(entry: Any) -> str | None:
    if not isinstance(entry, str):
        return None
    p = entry.strip()
    if _PERSON_RE.match(p):
        return p.lower()
    if _GROUP_RE.match(p):
        return p
    return None


def _parse_federation_scope(value: Any) -> FederationScope | None:
    """``"none"``/``"org"``/principal tuple (spec §12.1–12.2), None if unparseable.

    An empty list admits nobody, so it is ``"none"``.
    """
    if isinstance(value, str):
        v = value.strip().lower()
        return v if v in ("none", "org") else None
    if isinstance(value, list):
        principals = [_parse_principal(e) for e in value]
        if any(p is None for p in principals):
            return None
        canon = _dedup(p for p in principals if p is not None)
        return canon or "none"
    return None


def classify(rel_path: str, text: str | None, policy: Policy, *, unreadable: bool = False) -> Label:
    """Label one vault file (spec §5.3). Pure.

    ``rel_path`` is vault-relative and already normalised (:func:`normalize_rel`).
    ``text`` is the file's leading text, enough to include the closing
    frontmatter fence, or ``None`` for a non-markdown or missing file (path
    defaults only). ``unreadable=True`` says an existing markdown file could not
    be read (permission, a directory named ``x.md``, ...): it can't be
    inspected, so it is private, source ``forced``, warning ``file-unreadable``
    (fail closed; ``text`` is ignored).
    """
    rel = rel_path
    local_only = (_any(policy.local_only_always, rel) and not _any(policy.sync_allow, rel)) or _any(
        policy.local_only, rel
    )
    shared_by_path = _any(policy.shared_files, rel)
    warnings: list[str] = []

    if unreadable:
        return Label(
            path=rel,
            visibility="private",
            visibility_source="forced",
            local_only=local_only,
            shared_file=shared_by_path,
            warnings=("file-unreadable",),
        )

    try:
        fm = _frontmatter(text)
    except _Unparseable:
        return Label(
            path=rel,
            visibility="private",
            visibility_source="forced",
            local_only=local_only,
            shared_file=shared_by_path,
            warnings=("frontmatter-unparseable",),
        )

    visibility: Visibility
    source: VisibilitySource
    if fm is not None and "visibility" in fm:
        source = "frontmatter"
        parsed = _parse_visibility(fm["visibility"])
        if parsed is None:
            warnings.append("visibility-value")
            visibility = "private"
        else:
            visibility = parsed
    else:
        match = next((v for g, v in policy.visibility_defaults if glob_match(g, rel)), None)
        if match is None:
            visibility, source = "normal", "default"
        else:
            # Fail-closed for a hand-built Policy carrying an odd value.
            visibility = "normal" if match == "normal" else "private"
            source = "path_default"

    declared: FederationScope = "none"
    if fm is not None and "federation_scope" in fm:
        scope = _parse_federation_scope(fm["federation_scope"])
        if scope is None:
            warnings.append("visibility-value")
        else:
            declared = scope

    if visibility == "private" and declared != "none":
        warnings.append("privacy-contradiction")

    return Label(
        path=rel,
        visibility=visibility,
        visibility_source=source,
        federation_scope_declared=declared,
        local_only=local_only,
        shared_file=shared_by_path or declared != "none",
        warnings=_dedup(warnings),
    )


# ----- paths, readers, surfaces -------------------------------------------------


def _on_disk_case(root: Path, parts: tuple[str, ...]) -> tuple[str, ...]:
    """``parts`` with each existing component spelled as its directory entry.

    An exact entry name wins; otherwise a unique case-insensitive match is
    taken (a case-insensitive disk opens it under either spelling). From the
    first component that doesn't exist on, the rest stays as typed.
    """
    out: list[str] = []
    cur = root
    for i, part in enumerate(parts):
        try:
            with os.scandir(cur) as it:
                names = [e.name for e in it]
        except OSError:
            return (*out, *parts[i:])
        if part in names:
            real = part
        else:
            folded = [n for n in names if n.casefold() == part.casefold()]
            if len(folded) != 1:
                return (*out, *parts[i:])
            real = folded[0]
        out.append(real)
        cur = cur / real
    return tuple(out)


def normalize_rel(vault: Path, path: str | Path) -> str:
    """The vault-relative POSIX spelling of ``path``, symlinks and case resolved.

    Relative paths are taken from ``vault``. ``./``, ``..`` and symlinks
    (notably ``knowledge_base`` → ``knowledge-base``) are resolved, and every
    component that exists on disk takes its real entry name, so every spelling
    of one file (``Knowledge-Base/PERSONAL/t.md`` on a case-insensitive disk)
    gets the same label. Components that don't exist stay as typed. A leading
    ``knowledge_base`` segment (any case) is rewritten to ``knowledge-base``
    even when the symlink is absent. Raises ``ValueError`` for a path outside
    the vault or the vault root itself.

    Glob matching (``classify``) is case-sensitive, so whether a file such as
    ``.ENV`` matches ``.env*`` depends on its canonical on-disk name.
    """
    p = Path(path)
    if str(path) == "":
        raise ValueError("empty path")
    root = vault.resolve()
    target = (p if p.is_absolute() else vault / p).resolve()
    try:
        rel = target.relative_to(root)
    except ValueError:
        raise ValueError(f"path is outside the vault: {path}") from None
    parts = rel.parts
    if not parts:
        raise ValueError(f"path is the vault root: {path}")
    parts = _on_disk_case(root, parts)
    if parts[0].casefold() == _KB_ALIAS:
        parts = (_KB_DIR, *parts[1:])
    return "/".join(parts)


def visible_to(label: Label, reader: str) -> bool:
    """Whether ``reader`` may see the labelled file at all (spec §4.1, v1).

    ``owner`` and ``autonomous`` see every file (labelled); every
    ``agent:<principal>`` reader sees nothing in v1. Any other reader id is
    denied (fail-closed). The Agnes indexer applies its own rules (§9).
    """
    del label  # v1: the decision doesn't depend on the label yet (Stage 2 will)
    return reader in FULL_READERS


def surface_class(policy: Policy, surface: str) -> SurfaceClass:
    """``owner_only`` or ``shared`` for a surface id; unknown ids are ``shared``."""
    if surface in policy.shared_surfaces:
        return "shared"
    if surface in policy.owner_only_surfaces:
        return "owner_only"
    return "shared"
