"""The run ledger as a client contract: ``scoutctl runs --json`` (the app's Health panel).

One JSON document holding the recent rows of ``.scout-logs/run-outcomes.jsonl``, newest first, plus the
run-health report every other surface reads (``scout.health.evaluate``). The shape is versioned by
``schema_version``; a client must ignore keys it doesn't know, and a breaking change bumps the version.

No vault content leaves through here: a row carries the log's file name (never a path), enum-like
values checked against the shapes ``run-outcome.sh`` writes, numbers and timestamps. Findings are the
health report's own; a finding's ``detail`` is an error line only in a CLI, git or wrapper shape
(``health.FAILURE_LINE_RES`` must match at the start of the line, so the session's own prose never
comes through), its ``log`` is vault-relative (``.scout-logs/<name>``), and no finding text carries
the vault's or the home directory's absolute path.

The canonical example is ``tests/fixtures/contract/run-ledger.json``, generated by
``tests/unit/test_run_ledger_contract.py``; the macOS app keeps a byte copy (``contract.yml``).
"""

from __future__ import annotations

import re
from datetime import UTC, datetime, timedelta
from pathlib import Path

from scout import health
from scout.health import OutcomeRow, iso_z

SCHEMA_VERSION = 1
DEFAULT_SINCE = timedelta(days=7)
DEFAULT_LIMIT = 200
MAX_LIMIT = 2000

# Shapes a row's free-form-looking fields must have before they reach a client.
_LOG_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,120}\.log")
_CLASS_RE = re.compile(r"[a-z][a-z0-9_]{0,40}")
_COMMIT_RE = re.compile(r"[0-9a-f]{7,40}")
_SANDBOX = frozenset({"enforced", "unavailable", "off", "conflict", "failed"})
_SANDBOX_SOURCE = frozenset({"env", "switch"})
_INTEGRITY = frozenset({"clean", "restored", "unrestored", "error", "unchecked"})
_SLOT_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,80}")


def _pick(value: str | None, allowed: frozenset[str]) -> str | None:
    return value if value in allowed else None


def _match(value: str | None, pattern: re.Pattern[str]) -> str | None:
    return value if value is not None and pattern.fullmatch(value) else None


def run_dict(row: OutcomeRow) -> dict:
    """One ledger row as the contract shows it. Every key is always present (null when unknown)."""
    log = row.log.rsplit("/", 1)[-1] if row.log else None
    return {
        "slot": _match(row.slot, _SLOT_RE) or "unknown",
        "mode": _match(row.mode, _SLOT_RE) or "unknown",
        "runner": row.runner,
        "trigger": row.trigger,
        "started_at": iso_z(row.started_at),
        "finished_at": iso_z(row.finished_at),
        "duration_s": row.duration_s,
        "awake_s": row.awake_s,
        "exit_code": row.exit_code,
        # ok | failed | skipped_* (health.SKIP_OUTCOMES); a client treats an unknown value as "failed".
        "outcome": row.outcome,
        # Why: "ok", a failure class (timeout, rate_limited, oauth_expired, network, budget, git_lock, unknown)
        # or a skip's cause (gates_unsafe_*, lease_held, lease_unavailable).
        "failure_class": _match(row.failure_class, _CLASS_RE),
        "resets_at": iso_z(row.resets_at) if row.resets_at else None,
        "sandbox": _pick(row.sandbox, _SANDBOX),
        "sandbox_source": _pick(row.sandbox_source, _SANDBOX_SOURCE),
        "integrity": _pick(row.integrity, _INTEGRITY),
        "agent_runtime": row.agent_runtime,
        "model": row.model,
        "log": _match(log, _LOG_RE),
        "commits_in_window": row.commits_in_window,
        "newest_commit": _match(row.newest_commit, _COMMIT_RE),
    }


def _relative(text: str | None, *, vault: Path, home: Path | None) -> str | None:
    """``text`` with the vault's path dropped (vault-relative) and the home directory written as ``~``."""
    if not text:
        return text
    for root in {str(vault), str(vault.resolve())}:
        text = text.replace(root + "/", "")
    home_dir = str(home if home is not None else Path.home())
    return text.replace(home_dir + "/", "~/") if home_dir not in ("", "/") else text


def _finding_dict(finding: dict, *, vault: Path, home: Path | None) -> dict:
    """A health finding as the contract shows it: its log vault-relative (``.scout-logs/<name>``, or null
    when it isn't under the vault), and no absolute vault or home path in its text."""
    out = dict(finding)
    log = finding.get("log")
    if log:
        rel = _relative(log, vault=vault, home=home)
        out["log"] = rel if rel and not rel.startswith(("/", "~")) else None
    for key in ("summary", "fix", "detail"):
        out[key] = _relative(finding.get(key), vault=vault, home=home)
    return out


def parse_since(text: str, *, now: datetime) -> datetime:
    """``7d``, ``48h``, ``90m`` back from ``now``, or an ISO-8601 time (UTC when it has no zone)."""
    m = re.fullmatch(r"\s*(\d{1,5})\s*([dhm])\s*", text)
    if m:
        n, unit = int(m.group(1)), m.group(2)
        return now - {"d": timedelta(days=n), "h": timedelta(hours=n), "m": timedelta(minutes=n)}[unit]
    try:
        when = datetime.fromisoformat(text.strip().replace("Z", "+00:00"))
    except ValueError:
        raise ValueError(f"--since takes 7d, 48h, 90m or an ISO time, not {text!r}") from None
    return when if when.tzinfo else when.replace(tzinfo=UTC)


def ledger_report(
    vault: Path,
    *,
    now: datetime | None = None,
    since: datetime | None = None,
    limit: int = DEFAULT_LIMIT,
    home: Path | None = None,
) -> dict:
    """The ``scoutctl runs --json`` document: runs finished since ``since`` (newest first, at most
    ``limit``) and the run-health report."""
    now = now or datetime.now(UTC)
    since = since or now - DEFAULT_SINCE
    limit = max(1, min(limit, MAX_LIMIT))
    rows = [r for r in health.read_outcomes(vault) if r.finished_at >= since]
    rows.sort(key=lambda r: (r.finished_at, r.started_at), reverse=True)
    report = health.evaluate(vault, now=now, home=home)
    health_doc = report.to_dict()
    health_doc["findings"] = [_finding_dict(f, vault=vault, home=home) for f in health_doc["findings"]]
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_at": iso_z(now),
        "since": iso_z(since),
        "truncated": len(rows) > limit,
        "runs": [run_dict(r) for r in rows[:limit]],
        "health": health_doc,
    }
